"""Trace yd7_source.png (white logo on black) into an OpenSCAD polygon module."""
import cv2
import numpy as np

img = cv2.imread('yd7_source.png', cv2.IMREAD_GRAYSCALE)
img = cv2.resize(img, None, fx=2, fy=2, interpolation=cv2.INTER_CUBIC)
_, bw = cv2.threshold(cv2.GaussianBlur(img, (3, 3), 0), 128, 255, cv2.THRESH_BINARY)
contours, hier = cv2.findContours(bw, cv2.RETR_CCOMP, cv2.CHAIN_APPROX_NONE)
contours = [cv2.approxPolyDP(c, 0.8, True)[:, 0, :] for c in contours]
keep = [i for i, c in enumerate(contours) if abs(cv2.contourArea(c)) > 50]
pts = np.vstack([contours[i] for i in keep]).astype(float)
x0, y0 = pts.min(0)
x1, y1 = pts.max(0)
w, h = x1 - x0, y1 - y0
points, paths, n = [], [], 0
for i in keep:
    c = contours[i]
    p = [((x - x0) / w, (y1 - y) / w) for x, y in c]
    points += p
    paths.append(list(range(n, n + len(p))))
    n += len(p)
with open('yd7_outline.scad', 'w') as f:
    f.write('// Generated by trace.py from yd7_source.png. Unit width = 1.\n')
    f.write(f'yd7_aspect = {h / w:.5f};\n')
    f.write('module yd7_outline() polygon(points=[')
    f.write(','.join(f'[{x:.5f},{y:.5f}]' for x, y in points))
    f.write('], paths=[' + ','.join('[' + ','.join(map(str, p)) + ']' for p in paths) + ']);\n')
print('contours', len(keep), 'points', n, 'aspect', h / w)
